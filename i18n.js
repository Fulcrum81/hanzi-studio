/** Current language ('en' or 'ru') */
let currentLang = 'en';

/** Simple string replacement for placeholders like {char}, {n}, etc. */
function t(key, vars) {
  const locale = LOCALES[currentLang];
  let str = locale[key];
  if (str === undefined) {
    // fallback to English
    str = LOCALES.en[key] || key;
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), v);
    }
  }
  return str;
}

/** Apply translations to all elements with data-i18n attribute */
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    el.innerHTML = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key);
  });
}

/** Switch language and re-render all UI */
function switchLanguage(lang) {
  if (lang !== currentLang) {
    currentLang = lang;
    localStorage.setItem('hanzi-lang', lang);
    applyTranslations();
    // Dispatch a custom event so app.js can re-render dynamic text
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: currentLang } }));
  }
}

/** Load saved language preference */
function loadLanguage() {
  const saved = localStorage.getItem('hanzi-lang');
  if (saved === 'ru' || saved === 'en') {
    currentLang = saved;
  }
  applyTranslations();
}

