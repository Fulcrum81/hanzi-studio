// ---- Pinyin reverse index (plain latin в†’ characters) ----
// Built once from HANZI_DICT
// Maps a plain-pinyin string (no tone marks) to an array of { char, pinyin, definition }
const PINYIN_INDEX = (function buildPinyinIndex() {
  const map = {};
  const toneChars = /[ДЃГЎЗЋГ Д“Г©Д›ГЁД«Г­ЗђГ¬ЕЌГіЗ’ГІЕ«ГєЗ”Г№ГјЗ–ЗЗљЗњ]/;
  const stripTones = (s) =>
    s
      .toLowerCase()
      .replace(/[ДЃГЎЗЋГ ]/g, 'a')
      .replace(/[Д“Г©Д›ГЁ]/g, 'e')
      .replace(/[Д«Г­ЗђГ¬]/g, 'i')
      .replace(/[ЕЌГіЗ’ГІ]/g, 'o')
      .replace(/[Е«ГєЗ”Г№]/g, 'u')
      .replace(/[З–ЗЗљЗњ]/g, 'Гј')
      .replace(/[Гј]/g, 'v'); // also accept 'v' for 'Гј'

  for (const [ch, [pinyin, def]] of Object.entries(HANZI_DICT)) {
    if (ch.length !== 1) continue; // only index single chars for suggestions
    const plain = stripTones(pinyin);
    // Also index each space-separated syllable
    const syllables = plain.split(/\s+/);
    for (const syl of syllables) {
      if (!map[syl]) map[syl] = [];
      // Avoid duplicates
      if (!map[syl].find((e) => e.char === ch)) {
        map[syl].push({ char: ch, pinyin, pinyinPlain: plain, definition: def });
      }
    }
    // Whole plain pinyin
    if (!map[plain]) map[plain] = [];
    if (!map[plain].find((e) => e.char === ch)) {
      map[plain].push({ char: ch, pinyin, pinyinPlain: plain, definition: def });
    }
  }
  return map;
})();

// ---- Pinyin autocomplete ----
// Returns up to `max` entries that match given plain-latin prefix
function autocompletePinyin(prefix) {
  // Normalize: Гј в†’ v (PINYIN_INDEX keys use v, e.g. "nv" for еҐі)
  const q = prefix.trim().toLowerCase().replace(/[ГјЕ«ГєЗ”Г№]/g, 'v');
  if (!q || q.length < 1) return [];
  // Direct prefix match
  const exact = PINYIN_INDEX[q];
  const results = exact ? [...exact] : [];

  // Fuzzy: any key that starts with the prefix
  if (results.length < 10) {
    for (const [key, entries] of Object.entries(PINYIN_INDEX)) {
      if (key !== q && key.startsWith(q)) {
        for (const e of entries) {
          if (!results.find((r) => r.char === e.char)) {
            results.push(e);
            if (results.length >= 10) break;
          }
        }
        if (results.length >= 10) break;
      }
    }
  }
  return results.slice(0, 10);
}

// Helper: lookup by character OR by English/pinyin substring
function lookupHanzi(query) {
  const q = query.trim().toLowerCase();

  // Direct character match
  if (HANZI_DICT[q]) {
    return { char: q, pinyin: HANZI_DICT[q][0], definition: HANZI_DICT[q][1] };
  }

  // Try each char in a multi-char query: pick the first char that has data
  for (const ch of q) {
    if (HANZI_DICT[ch]) {
      return { char: ch, pinyin: HANZI_DICT[ch][0], definition: HANZI_DICT[ch][1] };
    }
  }

  // Search by English/definition or pinyin substring
  const matches = Object.keys(HANZI_DICT).filter((ch) => {
    const entry = HANZI_DICT[ch];
    return entry[1].toLowerCase().includes(q) || entry[0].toLowerCase().replace(/[ДЃГЎЗЋГ Д“Г©Д›ГЁД«Г­ЗђГ¬ЕЌГіЗ’ГІЕ«ГєЗ”Г№ГјЗ–ЗЗљЗњ]/g, '').includes(q.replace(/[ДЃГЎЗЋГ Д“Г©Д›ГЁД«Г­ЗђГ¬ЕЌГіЗ’ГІЕ«ГєЗ”Г№ГјЗ–ЗЗљЗњ]/g, ''));
  });

  if (matches.length > 0) {
    const ch = matches[0]; // first match
    return { char: ch, pinyin: HANZI_DICT[ch][0], definition: HANZI_DICT[ch][1] };
  }

  return null; // not found
}